import type { Env } from '../../worker/src/env.ts';

/** Build Worker-compatible Env from process.env (AWS App Runner / ECS / local). */
export function createNodeEnv(): Env {
  const e = process.env;
  return {
    ENVIRONMENT: (e.ENVIRONMENT as Env['ENVIRONMENT']) || 'production',
    API_CORS_ORIGIN: e.API_CORS_ORIGIN || 'https://app.malconnexus.com',
    DATABASE_URL: e.DATABASE_URL,
    PGSSL: e.PGSSL,
    PG_POOL_MAX: e.PG_POOL_MAX,
    API_REQUIRE_AUTH: e.API_REQUIRE_AUTH,
    SUPABASE_JWT_SECRET: e.SUPABASE_JWT_SECRET || e.JWT_SECRET,
    JWT_SECRET: e.JWT_SECRET,
    SUPABASE_JWT_AUD: e.SUPABASE_JWT_AUD,
    S3_BUCKET_STAGE_PHOTOS: e.S3_BUCKET_STAGE_PHOTOS,
    S3_BUCKET_ATTENDANCE_SELFIES: e.S3_BUCKET_ATTENDANCE_SELFIES,
    S3_BUCKET_HR_KYC_UPLOADS: e.S3_BUCKET_HR_KYC_UPLOADS,
    AWS_REGION: e.AWS_REGION,
    S3_PUBLIC_BASE_URL: e.S3_PUBLIC_BASE_URL,
    S3_SIGNED_URL_TTL: e.S3_SIGNED_URL_TTL,
    TELEGRAM_BOT_TOKEN: e.TELEGRAM_BOT_TOKEN,
    TELEGRAM_WEBHOOK_SECRET: e.TELEGRAM_WEBHOOK_SECRET,
    ALERT_CRON_SECRET: e.ALERT_CRON_SECRET,
    LOGIN_OTP_SECRET: e.LOGIN_OTP_SECRET,
    GALLERY_TOKEN: e.GALLERY_TOKEN,
    TV_BOARD_TOKEN: e.TV_BOARD_TOKEN,
    JWT_SECRET_PREVIOUS: e.JWT_SECRET_PREVIOUS,
  };
}
